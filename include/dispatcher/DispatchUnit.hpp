#pragma once                              // Предотвращает многократное подключение этого заголовочного файла
#include "dispatcher/DispatchTypes.hpp"   // Подключает типы и перечисления для диспетчерской системы (статусы, маркеры и т.п.)
#include <optional>                       // Подключает тип optional — позволяет хранить значение или отсутствие значения
#include <string>                         // Подключает стандартную библиотеку строк

namespace dispatcher {                    // Пространство имён для компонентов диспетчерской системы

class DispatchUnit {                      // Класс, описывающий диспетчерское подразделение (единицу)
public:
    DispatchUnit(int id, std::string name, std::string zone);  // Конструктор: создаёт подразделение с ID, именем и зоной ответственности

    int id() const;                                             // Возвращает уникальный идентификатор подразделения
    const std::string& name() const;                            // Возвращает имя подразделения (без копирования строки)
    const std::string& zone() const;                            // Возвращает зону ответственности подразделения
    UnitStatus status() const;                                  // Возвращает текущий статус подразделения (доступно, занято и т.д.)
    std::optional<int> assignedIncidentId() const;              // Возвращает ID назначенного инцидента или пустое значение, если ничего не назначено

    bool assignToIncident(int incidentId);                      // Назначает подразделение на указанный инцидент (возвращает успех операции)
    void release();                                             // Снимает подразделение с текущего инцидента
    void setMaintenance();                                      // Переводит подразделение в статус «на техобслуживании»
    void setOffline();                                          // Переводит подразделение в статус «недоступно»

private:
    int id_{};                                                   // Уникальный идентификатор подразделения
    std::string name_;                                           // Имя подразделения
    std::string zone_;                                            // Зона ответственности подразделения
    UnitStatus status_{UnitStatus::Available};                   // Текущий статус подразделения (по умолчанию — доступно)
    std::optional<int> assignedIncidentId_;                      // ID назначенного инцидента либо пустое значение (если инцидент не назначен)
};

} // namespace dispatcher